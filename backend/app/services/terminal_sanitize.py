from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 终端输出清洗
#
# 背景：增强会话（tmux）在 TUI 程序（opencode / vim / htop 等启用 SGR
# 鼠标模式或光标位置查询的程序）运行期间，tmux 的鼠标/渲染状态机可能把
# 控制序列的 CSI 前缀（"\x1b[" / "\x1b[<" / "\x1b[?") 吞掉，导致 pane
# 和回放缓冲里残留"裸控制序列"：
#   - 裸 SGR 鼠标事件      "35;82;22M35;81;22M..."（缺 "\x1b[<"）
#   - 裸 DSR 响应          "997;2n997;2n..."（缺 "\x1b[?"）
# 这些裸序列无法被终端正确渲染，直接回放会给用户造成满屏无意义字符。
#
# 注意：只在回放/缓冲侧做防御性清洗。真实、带完整前缀的控制序列（如
# "\x1b[1;1H" 光标定位）必须原样保留，否则会破坏终端渲染。
# ---------------------------------------------------------------------------

# 连续的裸控制序列 run：每段是 "数字;数字(;数字...)+ 字母"，段与段直接
# 拼接（允许中间被 tmux 软换行 "\n" 打断），run 整体替换为空。
# 段尾字母可能是 M/m（SGR 鼠标）、n/c（DSR 响应）。
# 允许多段连续出现（污染数据是连续刷出的），也允许单段。
# 结尾可能残留被截断的单数字（如 "...35;82;22M3"），一并吸收。
# 负向后顾排除 CSI 前缀成分（ESC / [ / ? / < / > / ; / 数字），
# 否则会把完整控制序列（如 "\x1b[<35;82;22M"）误判为裸序列。
_CSI_PREFIX_CHARS = r"\x1b[?<>;0-9"
_LEAD_SEGMENT = r"(?:[0-9]{1,3};){1,}[0-9]{1,3}|[0-9]{1,3}"
_SEGMENT = r"(?:[0-9]{1,3};){1,}[0-9]{1,3}[MmNnCc]"
# 首段允许无分号（截断残留如 "3M"），但必须后跟至少一个完整段，
# 避免把孤立单段（可能是正常内容）误删。结尾允许吸收被截断的单数字。
_BARE_SEQUENCE_RUN = re.compile(
    rf"(?<![{_CSI_PREFIX_CHARS}])(?:{_LEAD_SEGMENT})[MmNnCc]"
    rf"(?:{_SEGMENT})+"
    rf"(?:[0-9]{{1,3}})?",
)


def sanitize_terminal_output(data: str) -> str:
    """清洗回放/缓冲中的裸控制序列残留。

    只删除"缺 CSI 前缀、纯数字分号结构"的损坏序列，完整控制序列
    （带 ``\\x1b[`` / ``\\x1b[<`` / ``\\x1b[?`` 前缀）不受影响。

    例：
        "root@arm:~# 35;178;1M35;179;2M35;180;3M"  ->  "root@arm:~# "
        "997;2n997;2n"                              ->  ""
        "\\x1b[1;24r\\x1b[?1;2c"                    ->  "\\x1b[1;24r\\x1b[?1;2c"（原样）
    """
    if not data:
        return data
    return _BARE_SEQUENCE_RUN.sub("", data)
